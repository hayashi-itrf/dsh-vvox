import { readFile, writeFile } from 'node:fs/promises';
const root = new URL('../', import.meta.url);
const sources = await Promise.all(['lib/web-audio.js', 'lib/browser-player.js'].map(p => readFile(new URL(p, root), 'utf8')));
const runtime = sources.map(s => s.replace(/^import .*;\n/gm, '').replace(/^export /gm, '')).join('\n');
const ui = await readFile(new URL('client-ui.js', root), 'utf8');
await writeFile(new URL('client.js', root), '// Generated by scripts/build-client.mjs.\n' + ui.replace('/* AUDIO_RUNTIME */', runtime));
